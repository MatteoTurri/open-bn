/*
 * The DES key helpers: parity and the weak keys.
 */

#include "bsafe.h"

/* The 16 weak and semi-weak DES keys of the standard, 8 bytes each. */
static unsigned char DES_WEAK_KEYS[16][8] = {
    { 0x01, 0x01, 0x01, 0x01, 0x01, 0x01, 0x01, 0x01 },
    { 0xfe, 0xfe, 0xfe, 0xfe, 0xfe, 0xfe, 0xfe, 0xfe },
    { 0x1f, 0x1f, 0x1f, 0x1f, 0x1f, 0x1f, 0x1f, 0x1f },
    { 0xe0, 0xe0, 0xe0, 0xe0, 0xe0, 0xe0, 0xe0, 0xe0 },
    { 0x01, 0xfe, 0x01, 0xfe, 0x01, 0xfe, 0x01, 0xfe },
    { 0xfe, 0x01, 0xfe, 0x01, 0xfe, 0x01, 0xfe, 0x01 },
    { 0x1f, 0xe0, 0x1f, 0xe0, 0x0e, 0xf1, 0x0e, 0xf1 },
    { 0xe0, 0x1f, 0xe0, 0x1f, 0xf1, 0x0e, 0xf1, 0x0e },
    { 0x01, 0xe0, 0x01, 0xe0, 0x01, 0xf1, 0x01, 0xf1 },
    { 0xe0, 0x01, 0xe0, 0x01, 0xf1, 0x01, 0xf1, 0x01 },
    { 0x1f, 0xfe, 0x1f, 0xfe, 0x0e, 0xfe, 0x0e, 0xfe },
    { 0xfe, 0x1f, 0xfe, 0x1f, 0xfe, 0x0e, 0xfe, 0x0e },
    { 0x01, 0x1f, 0x01, 0x1f, 0x01, 0x0e, 0x01, 0x0e },
    { 0x1f, 0x01, 0x1f, 0x01, 0x0e, 0x01, 0x0e, 0x01 },
    { 0xe0, 0xfe, 0xe0, 0xfe, 0xf1, 0xfe, 0xf1, 0xfe },
    { 0xfe, 0xe0, 0xfe, 0xe0, 0xfe, 0xf1, 0xfe, 0xf1 }
};

/* BE_KEY_WEAK: weak key. A linear scan with T_memcmp on 8 bytes. */
int DESIsWeakKey(void *key)
{
    int i;
    unsigned char *p;

    for (i = 0, p = DES_WEAK_KEYS[0]; i < 16; i++) {
        if (T_memcmp(p, key, 8) == 0)
            return BE_KEY_WEAK;
        p += 8;
    }
    return 0;
}

/* Odd parity on the 7 high bits of each byte of the key: counts the 1 bits of the mask 128..2 and
 * sets bit 0 to make the count odd. */
void SetDESParity(void *key)
{
    unsigned char *p = (unsigned char *)key;
    unsigned int i;

    for (i = 0; i < 8; i++) {
        unsigned int mask;
        int count = 0;

        for (mask = 128; mask >= 2; mask >>= 1) {
            if (p[i] & mask)
                count++;
        }
        if (count & 1)
            p[i] &= 0xfe;
        else
            p[i] |= 1;
    }
}

/* Checks the parity on a copy (BE_WRONG_KEY_INFO: wrong parity). */
int CheckDESParity(void *key)
{
    unsigned char tmp[8];
    int status;

    T_memcpy(tmp, key, 8);
    SetDESParity(tmp);
    status = T_memcmp(tmp, key, 8) ? BE_WRONG_KEY_INFO : 0;
    T_memset(tmp, 0, 8);
    return status;
}
