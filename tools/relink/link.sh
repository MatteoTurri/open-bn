#!/bin/sh
# Link bn with ld 2.9EE, strip, DNAS protection and the post-link .compact_rel step.
#
# Usage: sh tools/relink/link.sh [extra ld options]   (repository root; `make link` calls it
#        after fetch.py, make_libs.py, link_order.py and make_blobs.py)
# Inputs: build/relink/link_order.txt and inputs.sha1 (link_order.py), the gate's .o files in
#   build/check/, the blobs and rebuilt .o files of build/relink/{blobs,merged}/ (make_blobs.py),
#   the libraries of build/relink/libs/ (make_libs.py), libgcc.a/crtbegin/crtend of build/relink/dl/
#   (fetch.py), crt1/crti/crtn of the kit, config/bn.x, config/relink_partial_r.txt.
#   Every constant (paths, binaries) comes from tools/relink/paths.py, the single source.
# Outputs (build/relink/), deleted at the start so that a failed run leaves no stale ones:
#   bn.unstripped.elf  ld output (with .mdebug/.symtab/.strtab), bn.map the ld map
#   bn.stripped.elf    mipsEEel-linux-strip 2.9EE with no options (the original is strip(link), not ld -s)
#   bn.protected.elf   bn.stripped.elf with DNAS descriptors and re-encrypted regions (dnas_protect.py)
#   bn.elf             bn.protected.elf with relvaddr and cpt.offset of .compact_rel copied from the
#                      original (compact_rel.py, rules in its docstring); compact_rel.log the report
# Fails if: a symbol is missing besides the 5 generated by the linker (missing_syms.py, override
#   RELINK_ALLOW_MISSING=1), the group of relink_partial_r.txt is not contiguous in link_order.txt
#   (partial_r.py), an input .o changed during the run (sha1 of inputs.sha1).
# Paths: all relative to the root and fixed. Those seen by `as` (e.g. build/relink/missing_data.s)
#   enter the .mdebug, hence bn.unstripped.elf and the cpt.offset written by ld (which compact_rel.py
#   replaces with the original's, so the SHA1 of bn.elf does not depend on them).
# Comparison: `make link-cmp` (tools/relink/cmp.py + SHA1).
# Output: on success one line (`linked build/relink/bn.elf`) plus the `warning:` lines that need
#   action; the reports of each step are in their .log/.txt in build/relink/ and with VERBOSE=1
#   (environment variable, to be passed into the container) they are printed too. ld warnings go to
#   build/relink/ld.log; those other than the known, harmless one about `tmpnam` (chloe_orange.c)
#   are printed.
set -e
V=${VERBOSE:-}
vlog() { if [ -n "$V" ]; then cat "$1"; fi; }
eval "$(python3 tools/relink/paths.py --sh)"
H=$OUT
rm -f $H/bn.unstripped.elf $H/bn.stripped.elf $H/bn.protected.elf $H/bn.elf $H/bn.elf.tmp $H/bn.map $H/partial_r.o
# The kit's crt1.o is used as is, .mdebug included (in link_order.txt with the kit path): ld
# creates .compact_rel in the dynobj (crt1.o) after its sections, so the two non-ALLOC orphans come
# out as .mdebug (24) and .compact_rel (25), as shown by the section symbols 24/25 of .dynsym and by
# cpt.offset of the original's .compact_rel (0xD827F0 = file position after 7,529,808 B of .mdebug).
# Dropping the .mdebug would swap their order in the file before the strip.
# Missing symbols (missing_syms.py): aliases and placeholders as --defsym, data as .comm; exits 1
# if a real one is missing (report on stderr and in missing_syms.txt)
python3 tools/relink/missing_syms.py > $H/missing_syms.log
vlog $H/missing_syms.log
$AS -mips2 -m5900 -o $H/missing_data.o $H/missing_data.s
DEFSYM=$(sed 's/^/--defsym /' $H/missing_defsym.txt | grep -v '^--defsym $' | tr '\n' ' ')
# Partial link: the original has 24 zero bytes in .fini between crtbegin and crtn, the signature
# of an `ld -r` (the -r script of ld 2.9EE ends .fini with QUAD(0)x3, like the kit's crt1.o).
# The objects of config/relink_partial_r.txt become one .o; partial_r.py checks that they are
# all in link_order.txt, contiguous and in the same order, and writes the final list objs.txt.
# Which group it was is a guess (the Chloe package); for the bytes it makes no difference.
python3 tools/relink/partial_r.py > $H/partial_r.log
vlog $H/partial_r.log
if [ -s $H/partial_r.txt ]; then
    $LD -m elf32lsmip -r -o $H/partial_r.o $(cat $H/partial_r.txt)
fi
OBJS=$(cat $H/objs.txt)
# order of the -l options = order of the original's DT_NEEDED (readelf -d): libfreetype,
# libpthread, libcrypt, libm, libdl, libstdc++, libocm, libc.
# -E (--export-dynamic): the original exports every defined global in .dynsym (9,694 entries).
# ld's stderr goes to ld.log; an error prints it whole, on success only the warnings other than the
# known one about tmpnam (the pair "In function `ChloeWatermelon':" + "the use of `tmpnam' is dangerous")
$LD -m elf32lsmip -dynamic-linker /lib/ld.so.1 -T $LDSCRIPT -o $H/bn.unstripped.elf -Map $H/bn.map \
    -E "$@" $DEFSYM $OBJS $H/missing_data.o -L$LIBS -rpath-link $LIBS \
    -lfreetype -lpthread -lcrypt -lm -ldl -lstdc++-libc6.2-2 -locm -lc \
    $LIBGCC 2> $H/ld.log || { cat $H/ld.log >&2; exit 1; }
if [ -n "$V" ]; then cat $H/ld.log >&2; else
    grep -v -e "In function \`ChloeWatermelon':" -e "the use of \`tmpnam' is dangerous" $H/ld.log \
        | sed 's/^/warning: ld: /' >&2 || true
fi
# the input .o files must not change during the run (tools/match or a concurrent make check
# recompiles build/check/): sha1 recorded by link_order.py
if ! sha1sum -c --quiet $INPUTS_SHA1; then
    rm -f $H/bn.unstripped.elf
    echo "error: input .o files changed during the link (listed above): rerun make check and make link" >&2
    exit 1
fi
# the original is strip(link): only this way PHDR has p_filesz 0xe0 (docs/linking.md)
$STRIP -o $H/bn.stripped.elf $H/bn.unstripped.elf
# DNAS protection: descriptors from the original (asset) and re-encryption of the 166 self-modifying
# regions with the parameters read from the linked binary (tools/relink/dnas_protect.py); exits 1 on
# model inconsistencies, not on differing regions
python3 tools/relink/dnas_protect.py $H/bn.stripped.elf $H/bn.protected.elf > $H/dnas_protect.log || { cat $H/dnas_protect.log >&2; exit 1; }
vlog $H/dnas_protect.log
# compact_rel.py copies relvaddr and cpt.offset from the original: bytes taken verbatim, meaningless for
# a modified bn (docs/original-bytes.md): whoever changes the program drops this step
python3 tools/relink/compact_rel.py $H/bn.protected.elf $H/bn.elf > $H/compact_rel.log || { cat $H/compact_rel.log >&2; exit 1; }
vlog $H/compact_rel.log
n=$(grep -c 'REJECTED' $H/compact_rel.log || true)
[ "$n" = 0 ] || echo "warning: compact_rel: $n .compact_rel entries rejected, see $H/compact_rel.log" >&2
echo "linked $H/bn.elf"
