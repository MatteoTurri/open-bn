#!/usr/bin/env python3
"""Symbols our .o files use that no .o / library of the link defines.

Usage: python3 tools/relink/missing_syms.py   (repository root, after link_order.py,
       make_libs.py, make_blobs.py; called by tools/relink/link.sh)

Normally the three outputs are empty except the report: it stays as a safety net,
because a new undefined symbol would make ld fail. For each missing symbol it looks
up the definition in the original's .dynsym and classifies it:
  alias    size-0 WEAK at the same address as a named function (e.g. scepfsClose,
           stat, lstat): the source lacks the alias (#pragma weak /
           __attribute__((alias))). Provisionally: --defsym alias=target (absolute
           symbol: st_shndx changes in .dynsym), lines in missing_defsym.txt;
  blob     falls inside a blob (asset, Chloe, DNAS): make_blobs.py places the label;
  data     object defined in the original (.data/.sbss/.bss) that none of our units
           defines (static members, TU variables without a unit): provisionally a
           .comm of the original size in missing_data.s (position not faithful);
  page     placeholder of a local GOT page (GOTPAGE below);
  unknown  not in the original's .dynsym.
Writes to build/relink/: missing_syms.txt (report), missing_defsym.txt, missing_data.s.
Exits 1 if a symbol is missing besides the 5 generated by the linker (paths.LINKER_GEN), with
the list on stderr; RELINK_ALLOW_MISSING=1 overrides it (for measuring only)."""
import glob, json, os, re, sys
from elftools.elf.elffile import ELFFile

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from paths import OUT as H, LIBS, LIBGCC_AR, ORIG, LINKER_GEN  # noqa: E402
# g_gmResBase1 + 29680 = 0x100b73f0 (start of the VU1 microcode, 0x3BD0 B) and
# g_gmResBase2 - 20544 = 0x100bafc0 (second program, 0x3FD0 B): the two 64 KB pages of the
# original's local GOT (from src/gfx/gm_graph.cpp and config/data_regions.txt)
GOTPAGE = {'g_gmResBase1': 0x100b0000, 'g_gmResBase2': 0x100c0000}


def syms(path, dyn=False):
    e = ELFFile(open(path, 'rb'))
    st = e.get_section_by_name('.dynsym' if dyn else '.symtab')
    d, u = {}, set()
    if st is None:
        return d, u
    for s in st.iter_symbols():
        if not s.name or s['st_info']['bind'] == 'STB_LOCAL':
            continue
        if s['st_shndx'] == 'SHN_UNDEF':
            u.add(s.name)
        else:
            d[s.name] = s
    return d, u


def main():
    o = json.load(open(f'{H}/order.json'))
    objs = [l.split('#')[0].strip() for l in open(f'{H}/link_order.txt') if l.strip() and not l.startswith('#')]
    defined, used = set(), set()
    for p in objs:
        d, u = syms(p)
        defined |= set(d)
        used |= u
    for lib in ('libc.so.6', 'libm.so.6', 'libpthread.so.0', 'libdl.so.2', 'libcrypt.so.1',
                'libstdc++-libc6.2-2.so.3', 'libocm.so', 'libfreetype.so.6'):
        d, _ = syms(f'{LIBS}/{lib}', dyn=True)
        defined |= {n.split('@')[0] for n in d}
    for p in glob.glob(LIBGCC_AR + '/*.o'):
        d, _ = syms(p)
        defined |= set(d)
    miss = sorted(used - defined - {'_gp_disp'})
    od, _ = syms(ORIG, dyn=True)
    byaddr = {}
    for n, s in od.items():
        if s['st_size'] and s['st_info']['type'] == 'STT_FUNC':
            byaddr.setdefault(s['st_value'], n)
    blobs = o['blobs']
    rep, defsym, data = [], [], []
    for n in miss:
        s = od.get(n)
        if n in GOTPAGE:
            rep.append(f'page    {n:50s} 0x{GOTPAGE[n]:08x} placeholder of the local GOT page (src/gfx/gm_graph.cpp: '
                       'in the original the VU1 microcode is local data of the .o, gotlocal debt)')
            defsym.append(f'{n}=0x{GOTPAGE[n]:08x}')
            continue
        if s is None:
            rep.append(f'unknown {n}')
            continue
        a, sz, t, b = s['st_value'], s['st_size'], s['st_info']['type'], s['st_info']['bind']
        bl = next((x for x in blobs if x['start'] <= a < x['end']), None)
        if bl:
            rep.append(f'blob    {n:50s} 0x{a:08x} {sz:6d} {t} in [{bl["name"]}]')
        elif sz == 0 and a in byaddr:
            rep.append(f'alias   {n:50s} 0x{a:08x} {b} -> {byaddr[a]}')
            defsym.append(f'{n}={byaddr[a]}')
        elif t == 'STT_OBJECT' or t == 'STT_NOTYPE':
            rep.append(f'data    {n:50s} 0x{a:08x} {sz:6d} {b}')
            data.append((n, max(sz, 1)))
        else:
            rep.append(f'other   {n:50s} 0x{a:08x} {sz:6d} {t} {b}')
    open(f'{H}/missing_syms.txt', 'w').write(
        f'# {len(miss)} symbols used and not defined in the link\n' + '\n'.join(rep) + '\n')
    open(f'{H}/missing_defsym.txt', 'w').write('\n'.join(defsym) + '\n')
    open(f'{H}/missing_data.s', 'w').write(
        '# Provisional definitions for the link (position not faithful to the original)\n\t.abicalls\n'
        + ''.join(f'\t.comm\t{n},{sz},{min(8, sz) if sz in (1, 2, 4, 8) else 8}\n' for n, sz in data))
    from collections import Counter
    if os.environ.get('VERBOSE') or '-v' in sys.argv[1:]:
        print('missing symbols by class: ' + ', '.join(f'{k} {v}' for k, v in sorted(Counter(r.split()[0] for r in rep).items())))
    # the only missing symbols allowed are the 5 generated by the linker; any other is a link
    # error (a new .o using a symbol without a definition): exit 1 with the list on stderr,
    # unless RELINK_ALLOW_MISSING=1 (for measuring: the provisional definitions above are used)
    bad = [r for n, r in zip(miss, rep) if n not in LINKER_GEN]
    if bad:
        print(f'error: {len(bad)} symbols used but not defined, besides the {len(LINKER_GEN)} generated by the linker '
              f'(report in {H}/missing_syms.txt):\n  ' + '\n  '.join(bad[:20])
              + (f'\n  ... and {len(bad) - 20} more' if len(bad) > 20 else ''), file=sys.stderr)
        if os.environ.get('RELINK_ALLOW_MISSING') != '1':
            sys.exit(1)
        print('warning: RELINK_ALLOW_MISSING=1, continuing with the provisional definitions', file=sys.stderr)


if __name__ == '__main__':
    main()
