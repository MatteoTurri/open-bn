#!/usr/bin/env python3
"""The self-modifying DNAS functions (generated lists).

They are part of the universe: the gate compares them whole with the decrypted
image, scaffold included (tools/dnas_ref.py, docs/dnas.md); the build
puts the scaffold in (tools/dnas_subst.py). There are two families with the
same cipher (verified bit for bit, see the self-test of tools/dnas1_crypt.py)
but two different setups:

  DNAS2 -- shim __sce_dnas2_symbol11002 / __sce_dnas2_symbol12002.
     List: config/dnas2_selfmod.txt, GENERATED by tools/dnas2_decrypt.py
     from its 125 regions.
  DNAS1 -- shim _sce_dnas_pwrap_main (0x5c5030) + _sce_dnas_pwrap_scramble/
     descramble + _sce_dnas_pwrap_clean_id.
     List: config/dnas1_selfmod.txt, GENERATED by tools/dnas1_decrypt.py
     from its 41 regions.

In both cases the function body contains the encrypted region plus the
descriptor (literal data) and the `b` jumps around it: gcc does not emit them
from C, and in our build tools/dnas_subst.py substitutes them in the `.s` in
place of the macros of src/dnas/dnas_prot.h, as Sony's tool did.
`python3 tools/dnas2_decrypt.py` and `python3 tools/dnas1_decrypt.py` write the
decrypted images to build/dnas/.

The lists are not written by hand: they are regenerated by the two tools.

This module is the one loader: tools/universe.py and tools/dnas_ref.py import it
from here, so they cannot diverge.
"""
import os

LISTS = ('config/dnas2_selfmod.txt', 'config/dnas1_selfmod.txt')
LIST = LISTS[0]   # backward compatibility


def _read(path):
    try:
        with open(path) as f:
            return {l.strip() for l in f
                    if l.strip() and not l.startswith('#')}
    except FileNotFoundError:
        return set()


def load(path=None):
    """Set of the self-modifying symbols. Without arguments it merges all the
    lists (`LISTS`); with an explicit `path` it reads only that one. A missing
    list counts as an empty set()."""
    if path is not None:
        return _read(path)
    out = set()
    for p in LISTS:
        out |= _read(p)
    return out


if __name__ == '__main__':
    for p in LISTS:
        s = _read(p)
        print('%-30s %4d functions%s' % (p, len(s),
                                        '' if os.path.exists(p) else '  (MISSING)'))
    print('%-30s %4d functions' % ('TOTAL (union)', len(load())))
