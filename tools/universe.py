#!/usr/bin/env python3
"""The one definition of the binary's function universe.

check.py and the other tools import it from here, so their counts cannot
diverge.

The sets, and the difference between them is the point:

  symbols()     every `type:func` row of config/symbol_addrs.txt (.dynsym)
                plus the unnamed functions of config/static_funcs.txt.
  alias()       those with size 0: aliases at the same address of a real
                symbol (e.g. scepfs* over scepfsd*). check.py skips them
                (`if not size: continue`), so they cannot be matched by
                construction and are not in the denominator.
  protected()   the self-modifying DNAS functions (tools/selfmod.py): they
                are in the universe, compared whole with the decrypted image
                (docs/dnas.md).

  achievable()  = symbols() - alias(): every function the gate compares.

`python3 tools/universe.py` prints the breakdown.
"""
import os
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import selfmod
import statics

SYMTAB = 'config/symbol_addrs.txt'
UNITS = 'config/units.txt'
CHECK = 'build/check.json'

SYM_RE = re.compile(
    r'^(\S+) = (0x[0-9A-Fa-f]+); // type:func size:(0x[0-9A-Fa-f]+)')


def dynsym(path=SYMTAB):
    """{name: (addr, size)} for every type:func row of config/symbol_addrs.txt
    (from .dynsym), aliases included. The named universe, without the statics."""
    out = {}
    for line in open(path):
        m = SYM_RE.match(line)
        if m:
            out[m.group(1)] = (int(m.group(2), 16), int(m.group(3), 16))
    return out


def statics_list():
    """{name: (addr, size)} of the unnamed functions (static + crt) from
    config/static_funcs.txt, a list GENERATED by tools/statics.py. Synthetic
    name `static_<ADDR>`. Empty if the list is missing."""
    return statics.load()


def is_static(sym):
    return statics.is_static(sym)


def symbols(path=SYMTAB):
    """{name: (addr, size)}: .dynsym (aliases included) union statics. The
    universe includes the unnamed functions too (tools/statics.py)."""
    out = dynsym(path)
    out.update(statics_list())
    return out


def alias(syms=None):
    """Names with size 0 (aliases of a real symbol at the same address)."""
    syms = symbols() if syms is None else syms
    return {n for n, (_, sz) in syms.items() if not sz}


def protected(syms=None):
    """Names of the self-modifying DNAS functions (config/dnas{1,2}_selfmod.txt
    plus the statics intersecting an encrypted region, tools/dnas_ref.py),
    restricted to the universe. They are inside the achievable universe: the
    gate compares them whole with the decrypted image, scaffold included
    (tools/dnas_ref.py, docs/dnas.md)."""
    syms = symbols() if syms is None else syms
    import dnas_ref
    return dnas_ref.protected(syms) & set(syms)


def achievable(syms=None):
    """{name: (addr, size)} of the achievable universe: the denominator."""
    syms = symbols() if syms is None else syms
    return {n: v for n, v in syms.items() if v[1]}


def skips(path=UNITS):
    """Symbols in the skip column of config/units.txt: they have a written body
    but the gate leaves them out."""
    out = set()
    for raw in open(path):
        raw = raw.strip()
        if not raw or raw.startswith('#'):
            continue
        parts = [p.strip() for p in raw.split('|')]
        if len(parts) > 3:
            out |= set(filter(None, parts[3].split(',')))
    return out


if __name__ == '__main__':
    s = symbols()
    a, ac = alias(s), achievable(s)
    nb = lambda d: sum(sz for _, sz in d.values())
    print('type:func rows    %5d   %9d bytes' % (len(s), nb(s)))
    print('  - alias size 0  %5d   %9d bytes  (check.py skips them)' % (len(a), 0))
    p = protected(s)
    print('  (DNAS protected %5d   %9d bytes  included, reference: decrypted image)'
          % (len(p), sum(s[n][1] for n in p)))
    print('  = achievable    %5d   %9d bytes  (compared by the gate)'
          % (len(ac), nb(ac)))
